from __future__ import annotations

import json
from pathlib import Path
from typing import Optional, Dict, Any
from config import Config
from models.clinical_schemas import ClinicalDossier


class DossierGeneratorService:
    """
    Synthesizes ClinicalDossier objects into high-density English medical summaries
    tailored specifically for rural CHC doctors to solve the 3-minute OPD review bottleneck.
    Saves and renders both structured JSON files and printable Markdown OPD records.
    """

    def __init__(self, storage_dir: Optional[Path] = None) -> None:
        self.storage_dir = storage_dir or Config.DOSSIERS_DIR
        self.storage_dir.mkdir(parents=True, exist_ok=True)

    def save_dossier(self, dossier: ClinicalDossier, ticket_id: Optional[str] = None) -> Dict[str, str]:
        """
        Persist the clinical dossier to disk as both JSON and formatted Markdown.
        Returns paths to the saved files.
        """
        ref_id = ticket_id or dossier.dossier_id
        json_path = self.storage_dir / f"{ref_id}.json"
        md_path = self.storage_dir / f"{ref_id}_opd_slip.md"

        # 1. Save JSON
        with open(json_path, "w", encoding="utf-8") as f:
            f.write(dossier.json(indent=2))

        # 2. Render and save Doctor's High-Density Markdown Dossier
        md_content = self.render_doctor_markdown(dossier, ticket_id=ref_id)
        with open(md_path, "w", encoding="utf-8") as f:
            f.write(md_content)

        return {"json_path": str(json_path), "md_path": str(md_path)}

    def load_dossier(self, ref_id: str) -> Optional[ClinicalDossier]:
        """Load a persisted clinical dossier by ticket ID or dossier ID."""
        json_path = self.storage_dir / f"{ref_id}.json"
        if not json_path.exists():
            return None
        with open(json_path, "r", encoding="utf-8") as f:
            data = json.load(f)
            return ClinicalDossier.parse_obj(data)

    def render_doctor_markdown(self, dossier: ClinicalDossier, ticket_id: str = "TICKET-PENDING") -> str:
        """
        Format the ClinicalDossier into a 3-minute high-density English OPD Clinical Slip.
        """
        s = dossier.subjective
        o = dossier.objective
        a = dossier.assessment
        p = dossier.plan

        # Format past prescription medications table
        med_rows = ""
        if o.ocr_prescriptions:
            for m in o.ocr_prescriptions:
                med_rows += f"| {m.drug_name} | {m.dosage} | {m.frequency} | {m.duration or 'N/A'} | {int(m.confidence*100)}% |\n"
        else:
            med_rows = "| None reported / No prior prescription slip uploaded | - | - | - | - |\n"

        # Format visual exam findings
        visual_rows = ""
        if o.visual_photo_findings:
            for v in o.visual_photo_findings:
                visual_rows += f"- **{v.body_location}**: {v.morphology} *(Severity: {v.severity}, Suspicion: {v.suspicion})*\n"
        else:
            visual_rows = "- Visual inspection: No overt cutaneous lesions submitted.\n"

        # Format differential diagnoses
        diff_list = "\n".join([f"  {d}" for d in a.differential_diagnoses])

        # Format investigations
        inv_list = "\n".join([f"- [ ] {inv}" for inv in p.suggested_investigations])

        # Format red flags
        rf_list = "\n".join([f"- ⚠️ {rf}" for rf in p.red_flag_warnings])

        # Urgency indicator
        urgency_badge = f"**[{a.triage_urgency.value}]**"
        if dossier.is_emergency:
            urgency_badge = "🚨 **CRITICAL EMERGENCY (108 SOS TRIGGERED)**"

        slip = f"""# CARE-ROUTE (केयररूट) CLINICAL PRE-INTAKE DOSSIER
**Community Health Center (CHC) Outpatient Department (OPD)**
*Generated by CareRoute Autonomous Telehealth Protocol*

---

### PATIENT INTAKE SUMMARY
- **Ticket ID**: `{ticket_id}`
- **Dossier UUID**: `{dossier.dossier_id}`
- **Patient Identifier**: `{dossier.patient_name}` (`{dossier.patient_id}`)
- **Timestamp**: `{dossier.created_at}`
- **Triage Level**: {urgency_badge}
- **Target Specialty**: **{a.recommended_specialty}** ({a.recommended_specialty_hindi})

---

### [S] SUBJECTIVE (Patient Narrative & Vernacular Intake)
- **Raw Vernacular Complaint (Hindi)**:
  > *"{s.patient_chief_complaint_hindi}"*
- **Clinical English Chief Complaint**:
  **{s.chief_complaint_english}**
- **Duration / Timeline**: `{s.symptom_duration}`
- **History of Present Illness (HPI)**:
  {s.history_of_present_illness}
- **Associated Systemic Symptoms**:
  {', '.join(s.associated_symptoms) if s.associated_symptoms else 'None reported'}
- **Prior Medical History**:
  {', '.join(s.past_medical_history) if s.past_medical_history else 'Non-contributory'}

---

### [O] OBJECTIVE (VLM Visual Findings & Prescription OCR)
- **Reported Vitals**:
  {', '.join([f'{k}: {v}' for k, v in o.vitals_reported.items()]) if o.vitals_reported else 'Vital signs stable at intake screening'}
- **Multimodal Visual / Photo Findings**:
{visual_rows}
- **OCR Parsed Past Medications (Handwritten Prescription Slip)**:

| Medication Name | Strength / Dose | Regimen / Frequency | Duration | OCR Confidence |
| :--- | :--- | :--- | :--- | :--- |
{med_rows}
- **Objective Clinical Assessment Note**:
  {o.clinical_signs_summary}

---

### [A] ASSESSMENT (Differential Triage & Clinical Rationale)
- **Ranked Differential Diagnoses**:
{diff_list}

- **Clinical Rationale & Triage Decision**:
  {a.clinical_rationale}

---

### [P] PLAN (Targeted Investigations & OPD Action Plan)
- **Suggested Point-of-Care Investigations (CHC Lab Checklist)**:
{inv_list}

- **Red-Flag Tripwires Monitored**:
{rf_list}

- **Interim Patient Guidance Given in Hindi**:
  > *"{p.interim_patient_advice_hindi}"*

---
*Verified by CareRoute Agent Protocol | Anti-No-Show Escrow: 0.5 FET Verified*
"""
        return slip
